"""Grammar properties of each function set (tool T11; docs/design/measurement.md, brief §7.4). Exploratory inputs for
explaining set-level differences (H2 step 6). All values come from files: enumeration counts and levels, the Phase 1
report (bits per node, float-noise duplicates) and the operator probe (undefined and neutral shares).

    .venv/bin/python -m reach.analysis.s2.properties      -> data/analysis/properties.json, docs/status/properties_report.md
"""
import json

import numpy as np

from reach import grammar as G
from reach.enumerate import _coeffs, read_level, real_keys

REAL_KEYS = {"x_plus_1": lambda x: x + 1, "x_squared": lambda x: x * x, "x_cubed": lambda x: x ** 3,
             "exp": np.exp, "log": np.log, "inverse": lambda x: 1 / x}


def _bool_keys(n):
    vm = G.var_masks(n)
    x1, x2, x3 = vm["x1"], vm["x2"], vm["x3"]
    return {"and2": x1 & x2, "or2": x1 | x2, "xor2": x1 ^ x2, "parity3": x1 ^ x2 ^ x3,
            "majority3": (x1 & x2) | (x1 & x3) | (x2 & x3), "not1": ((1 << (1 << n)) - 1) ^ x1}


def key_sizes(g, enum_dir):
    """Minimum size of a few key functions in the set (None if absent up to the ceiling)."""
    if g.kind == "real":
        xs = G.sample_grid(g)
        c = _coeffs(2 * G.N_POINTS)
        with np.errstate(all="ignore"):
            want = {k: int(real_keys(np.asarray(f(xs), complex)[None, :], c)[0]) for k, f in REAL_KEYS.items()}
    else:
        want = {k: int(v) for k, v in _bool_keys(g.n_inputs).items()}
    out = {k: None for k in want}
    stats = json.loads((enum_dir / "counts.json").read_text())["levels"]
    for st in stats:
        keys = read_level(enum_dir / f"level_{st['K']:03d}.npz")[0]
        hit = np.isin(np.array(list(want.values()), dtype=np.uint64), keys)
        for (k, _), h in zip(want.items(), hit):
            if h and out[k] is None:
                out[k] = st["K"]
    return out


def redundancy(levels, K):
    """Syntactic trees per distinct function at size K: N_G(K) / U_G(K)."""
    st = next(s for s in levels if s["K"] == K)
    return st["N_syntactic"] / st["U"] if st["U"] else float("nan")


def build():
    from reach import s2_sets as S
    from reach.analysis.s2.phase1 import enum_dir, lam
    from reach.paths import ROOT
    probe = json.loads((ROOT / "data/analysis/opprobe.json").read_text()) if (ROOT / "data/analysis/opprobe.json").exists() else {}
    from reach.tasks.s2_random_draw import heldout_from_files
    res = {}
    rnd = heldout_from_files(ROOT)
    for name in list(S.SETS) + rnd["real"] + rnd["bool"]:             # listed sets and the random held-out sets
        g, d = G.get(name), enum_dir(name)
        if not (d / "counts.json").exists():
            continue
        levels = json.loads((d / "counts.json").read_text())["levels"]
        a0, a1, a2 = g.arity_counts()
        k_red = max((s["K"] for s in levels if s["U"] > 0 and s["K"] <= 9), default=None)
        pr = probe.get(name, {}).get("subtree_mutation", {})
        res[name] = dict(domain=g.kind, bits_per_node=lam(levels), alphabet=a0 + a1 + a2, terminals=a0, unary=a1,
                         binary=a2, ceiling=max(s["K"] for s in levels if s["U"] > 0),
                         redundancy_K=k_red, redundancy=redundancy(levels, k_red) if k_red else None,
                         undefined_share_initial=(1 - pr["defined_parent_share"]) if pr else None,
                         neutral_share_mutation=(1 - pr["changed_share_defined"]) if pr else None,
                         key_sizes=key_sizes(g, d))
    return res


def main():
    from reach.paths import ROOT
    res = build()
    (ROOT / "data/analysis/properties.json").write_text(json.dumps(res, indent=1, default=float))
    f = lambda x, d=2: "–" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))       # noqa
    L = ["# Grammar properties (T11)", "", "> Index: `docs/README.md`. Generated by `reach.analysis.s2.properties`; values in "
         "`data/analysis/properties.json`. Exploratory inputs (H2 step 6).", "",
         "| Set | bits/node | alphabet (t/u/b) | ceiling | trees per function (K) | undefined initial | neutral mutation | key sizes |",
         "|---|---|---|---|---|---|---|---|"]
    for n, r in res.items():
        ks = ", ".join(f"{k} {v}" for k, v in r["key_sizes"].items() if v is not None)
        L.append(f"| {n} | {f(r['bits_per_node'])} | {r['alphabet']} ({r['terminals']}/{r['unary']}/{r['binary']}) | "
                 f"{r['ceiling']} | {f(r['redundancy'], 1)} ({r['redundancy_K']}) | {f(r['undefined_share_initial'])} | "
                 f"{f(r['neutral_share_mutation'])} | {ks} |")
    (ROOT / "docs/status/properties_report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
